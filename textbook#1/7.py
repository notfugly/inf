from math import log2


n = 8
# постепенно увеличиваем "перекос" распределения:
# доля первого сообщения растет, остальные делят остаток поровну
for p1 in [1/8, 0.2, 0.3, 0.5, 0.7, 0.9, 0.99]:
    p = [p1] + [(1 - p1) / (n - 1)] * (n - 1)
    H = -sum(pi * log2(pi) for pi in p)
    print("p1 =", round(p1, 2), "H =", round(H, 4), "log2(n) =", log2(n))

# чем сильнее перекос, тем меньше энтропия,
# максимум H = log2(n) достигается при равномерном распределении