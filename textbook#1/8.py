from math import log2


n = 8
hartley = log2(n)   # зависит только от числа сообщений

cases = {
    "равномерное":  [1/n] * n,
    "слабо неравномерное": [0.2] + [(1 - 0.2)/(n-1)] * (n-1),
    "средне неравномерное": [0.5] + [(1 - 0.5)/(n-1)] * (n-1),
    "сильно неравномерное": [0.9] + [(1 - 0.9)/(n-1)] * (n-1),
}

print("N =", n, "-> Хартли I = log2(N) =", round(hartley, 4))
for name, p in cases.items():
    H = -sum(pi * log2(pi) for pi in p)
    print(name, "H Шеннона =", round(H, 4), "| разница I - H =", round(hartley - H, 4))

# вывод:
# Хартли учитывает только число сообщений N и не зависит от вероятностей.
# Шеннон учитывает вероятности: при равномерном распределении H = log2(N),
# при неравномерном H < log2(N). Чем сильнее перекос, тем меньше H.